/** Icons drawn on a 16px grid; the rest use 24px */
const SMALL_GRID_ICONS = new Set<RIconName>([
  "sort",
  "dots",
  "copy-16",
  "link-16",
]);

export function RIcon({
  name,
  size = "medium",
  title,
  className,
  sortDirection,
  isSpinning = false,
  ...props
}: RIconProps) {
  const titleId = useId();
  const Icon = name === "link" ? LinkIcon : "svg";

  return (
    <Icon
      aria-hidden={title ? undefined : true}
      aria-labelledby={title ? titleId : undefined}
      className={clsx(
        styles.icon,
        styles[size],
        (isSpinning || name === "loading" || name === "loading-progress") &&
          styles.spin,
        className
      )}
      fill="none"
      focusable="false"
      data-sort-direction={name === "sort" ? sortDirection : undefined}
      data-sort-icon={name === "sort" || undefined}
      role={title ? "img" : undefined}
      stroke="currentColor"
      strokeLinecap="round"
      strokeLinejoin="round"
      strokeWidth={name === "sort" ? 1 : 1.5}
      viewBox={SMALL_GRID_ICONS.has(name) ? "0 0 16 16" : "0 0 24 24"}
      {...props}
    >
      {title ? <title id={titleId}>{title}</title> : null}
      {rIconPaths[name]}
    </Icon>
  );
}
