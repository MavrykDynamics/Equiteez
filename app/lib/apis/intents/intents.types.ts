/** Backend codes plus client-side transport/validation failures. */
export type IntentErrorCode =
  | (typeof intentErrorCodes)[number]
  /** The service could not be reached (offline, DNS, CORS, timeout). */
  | "NETWORK"
  /** A response did not match the contract. */
  | "INVALID_RESPONSE"
  /** A backend code this client does not know. */
  | "UNKNOWN";

/**
 * Operation scope, generated by the client and persisted with the request
 * BEFORE the first POST. Retries reuse all three (backend.md §5). The
 * capability is a bearer secret: never put it in URLs, logs or analytics.
 */
export type IntentCredentials = {
  capability: string;
  idempotencyKey: string;
};

type RequestOptions = { signal?: AbortSignal };

/** The only surface UI code uses; mock and HTTP clients both implement it. */
export interface IntentsApi {
  readonly env: string;
  /**
   * `GET /v1/metadata`; no capability. Settlement tokens and the source
   * assets offered now. Invalid entries are dropped.
   */
  getMetadata(options?: RequestOptions): Promise<IntentMetadata>;
  /** `POST /v1/quotes/preview`; no capability. Indicative, creates nothing. */
  previewQuote(
    request: IntentPreviewRequest,
    options?: RequestOptions
  ): Promise<IntentPreview>;
  /**
   * `POST /v1/operations` → 202. The operation is durable; it does not yet
   * have a quote. `replayed` is the `Idempotency-Replayed` header.
   */
  createOperation(
    credentials: IntentCredentials,
    request: IntentOperationRequest,
    options?: RequestOptions
  ): Promise<{ operation: IntentOperation; replayed: boolean }>;
  /** `GET /v1/operations/:id`; read-only, never creates a new quote. */
  getOperation(
    capability: string,
    operationId: string,
    options?: RequestOptions
  ): Promise<IntentOperation>;
}

/** Typed failure. Branch on `code`/`status`, never on the message. */
export class IntentsApiError extends Error {
  constructor(
    readonly code: IntentErrorCode,
    message: string,
    readonly status?: number,
    /** Server request ID for support; safe to show. */
    readonly requestId?: string,
    /** From `Retry-After` on 429/503. */
    readonly retryAfterMs?: number
  ) {
    super(message);
    this.name = "IntentsApiError";
  }
}

export const isIntentsApiError = (error: unknown): error is IntentsApiError =>
  error instanceof IntentsApiError;
