import type { z } from "zod";
import type {
  intentAttentionSchema,
  intentClosureSchema,
  intentErrorCodes,
  intentFundingInstructionsSchema,
  intentFundingStatusSchema,
  intentMetadataRouteSchema,
  intentOperationRequestSchema,
  intentOperationSchema,
  intentPhaseSchema,
  intentProviderStatusSchema,
  intentRouteSchema,
} from "./intents.schema";

export type IntentRoute = z.infer<typeof intentRouteSchema>;
export type IntentMetadataRoute = z.infer<typeof intentMetadataRouteSchema>;
/** `GET /v1/metadata`; `null` when the deployment does not expose it. */
export type IntentMetadata = {
  admissionPaused: boolean;
  routes: IntentMetadataRoute[];
};
export type IntentOperationRequest = z.infer<
  typeof intentOperationRequestSchema
>;
export type IntentOperation = z.infer<typeof intentOperationSchema>;
export type IntentFundingInstructions = z.infer<
  typeof intentFundingInstructionsSchema
>;
export type IntentPhase = z.infer<typeof intentPhaseSchema>;
export type IntentAttention = z.infer<typeof intentAttentionSchema>;
export type IntentClosure = z.infer<typeof intentClosureSchema>;
export type IntentFundingStatus = z.infer<typeof intentFundingStatusSchema>;
export type IntentProviderStatus = z.infer<typeof intentProviderStatusSchema>;

/** Backend codes plus client-side transport/validation failures. */
export type IntentErrorCode =
  | (typeof intentErrorCodes)[number]
  /** The service could not be reached (offline, DNS, CORS, timeout). */
  | "NETWORK"
  /** A response did not match the contract. */
  | "INVALID_RESPONSE"
  /** A backend code this client does not know. */
  | "UNKNOWN";

/**
 * Operation scope, generated by the client and persisted with the request
 * BEFORE the first POST. Retries reuse all three (backend.md §2). The
 * capability is a bearer secret: never put it in URLs, logs or analytics.
 */
export type IntentCredentials = {
  capability: string;
  idempotencyKey: string;
};

type RequestOptions = { signal?: AbortSignal };

/** The only surface UI code uses; mock and HTTP clients both implement it. */
export interface IntentsApi {
  readonly env: string;
  /** `GET /v1/routes`; no capability. Invalid entries are dropped. */
  getRoutes(options?: RequestOptions): Promise<IntentRoute[]>;
  /**
   * `POST /v1/operations` → 202. The operation is durable; it does not yet
   * have a quote. `replayed` is the `Idempotency-Replayed` header.
   */
  createOperation(
    credentials: IntentCredentials,
    request: IntentOperationRequest,
    options?: RequestOptions
  ): Promise<{ operation: IntentOperation; replayed: boolean }>;
  /** `GET /v1/operations/:id`; read-only, never creates a new quote. */
  getOperation(
    capability: string,
    operationId: string,
    options?: RequestOptions
  ): Promise<IntentOperation>;
  /**
   * `GET /v1/metadata`; no capability. Asset identities per route version.
   * `null` when the endpoint is not deployed (no asset is inferred then).
   * Invalid entries are dropped.
   */
  getMetadata(options?: RequestOptions): Promise<IntentMetadata | null>;
  /**
   * `POST /v1/operations/:id/deposit` (backend.md §4.5): binds the wallet's
   * funding transaction to the operation. Idempotent for the same hash
   * (`replayed: true`). `REHEARSAL_RECEIPT_PENDING` means: send the same hash
   * again later, never ask the wallet again.
   */
  registerDeposit(
    capability: string,
    operationId: string,
    transactionHash: `0x${string}`,
    options?: RequestOptions
  ): Promise<{ replayed: boolean }>;
}

/** Typed failure. Branch on `code`/`status`, never on the message. */
export class IntentsApiError extends Error {
  constructor(
    readonly code: IntentErrorCode,
    message: string,
    readonly status?: number,
    /** Server request ID for support; safe to show. */
    readonly requestId?: string,
    /** From `Retry-After` on 429/503. */
    readonly retryAfterMs?: number
  ) {
    super(message);
    this.name = "IntentsApiError";
  }
}

export const isIntentsApiError = (error: unknown): error is IntentsApiError =>
  error instanceof IntentsApiError;
